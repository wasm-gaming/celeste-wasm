#!/usr/bin/env node
// Give the loader a configurable place in storage, instead of the root.
//
// The loader mounts the origin private filesystem at /libsdl and then reads and
// writes absolute paths under it — `/libsdl/Celeste.exe`, `/libsdl/Content`,
// `/libsdl/Celeste/Saves` and so on. Because the mount *is* the origin's root,
// every one of those is a top-level OPFS entry, so a page that runs this engine
// beside another cannot keep the two apart: Celeste claims `Content/`,
// `Celeste.exe` and whatever else the player's folder held, at the root, for the
// whole origin.
//
// This rewrites those literals to go through one pair of roots, and adds a
// parameter to `MountFilesystems` that sets them. Everything then lands under
// `/libsdl/<namespace>/`, which is an ordinary OPFS directory the host chooses.
//
// Two roots rather than one, because the loader has two today: the install sits
// at the mount (`/libsdl/Content`) and the mutable state one level down
// (`/libsdl/Celeste/Saves`). Keeping them separate means an empty namespace
// reproduces the current layout byte for byte — which is what makes this
// upstreamable, and what lets a build opt out.
//
//   usage: patch-loader-source.mjs <loader-checkout>
//   env:   LOADER_NAMESPACE   default namespace baked in (default: celeste)

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const srcDir = process.argv[2];
if (!srcDir) {
  console.error('usage: patch-loader-source.mjs <loader-checkout>');
  process.exit(1);
}

const namespace = process.env.LOADER_NAMESPACE ?? 'celeste';
if (namespace && !/^[A-Za-z0-9._-]+$/.test(namespace)) {
  console.error(`[patch] LOADER_NAMESPACE must be a single path segment, got ${JSON.stringify(namespace)}`);
  process.exit(1);
}

const changes = [];

/** Rewrite a file, failing loudly when an expected anchor is not there. */
function edit(rel, apply) {
  const path = join(srcDir, rel);
  const before = readFileSync(path, 'utf8');
  const after = apply(before, rel);
  if (after === before) {
    console.error(`[patch] nothing to change in ${rel} — upstream has moved`);
    process.exit(1);
  }
  writeFileSync(path, after);
}

// ------------------------------------------------------------ the two roots --

{
  const rel = 'loader/CelestePaths.cs';
  writeFileSync(
    join(srcDir, rel),
    `// Generated by scripts/patch-loader-source.mjs in @wasm-gaming/celeste-wasm.
//
// Where the game lives inside the OPFS mount. Both default to the layout that
// shipped before this was configurable, so an empty namespace is a no-op.

public static class CelestePaths
{
    /// <summary>Where Emscripten.c mounts the origin private filesystem.</summary>
    public const string Mount = "/libsdl";

    /// <summary>The player's install: Content/, Celeste.exe, the patched assemblies.</summary>
    public static string Install { get; private set; } = Mount;

    /// <summary>Mutable state: Everest/, Mods/, Saves/.</summary>
    public static string State { get; private set; } = Mount + "/Celeste";

    /// <summary>
    /// Put both under one directory of the mount. Empty restores the default
    /// two-level layout.
    /// </summary>
    public static void UseNamespace(string ns)
    {
        if (string.IsNullOrEmpty(ns))
        {
            Install = Mount;
            State = Mount + "/Celeste";
        }
        else
        {
            // A pure prefix of the default layout, rather than collapsing the
            // two levels into one. "celeste/Celeste/Saves" reads oddly, but it
            // means a host only ever prepends one segment to reach anything —
            // one code path for a namespaced runtime and a stock one, instead
            // of two layouts to tell apart.
            Install = Mount + "/" + ns;
            State = Install + "/Celeste";
        }

        // The MonoMod patch mod that supplies Everest's paths is a separate
        // assembly with no reference to this one, so the value crosses through
        // the environment rather than a static.
        System.Environment.SetEnvironmentVariable("CELESTE_STATE", State);
    }
}
`,
  );
  changes.push(`${rel}: generated (default namespace "${namespace || '(none)'}")`);
}

// --------------------------------------------------------------- the paths --
//
// Every literal is `"/libsdl/…"` or `$"/libsdl/…"`, so one pass per root does
// the lot. The `$` is added when it is not already there, which turns a plain
// string into an interpolated one — safe here because none of the affected
// literals contain a brace.

const STATE_PREFIX = /(\$?)"\/libsdl\/Celeste\//g;
const INSTALL_PREFIX = /(\$?)"\/libsdl\//g;

function rewritePaths(source, rel) {
  // The `$` has to be inside the match, or every already-interpolated literal
  // looks like a plain one about to be broken.
  const braces = [...source.matchAll(/\$?"[^"\n]*\/libsdl\/[^"\n]*"/g)].filter(
    (m) => !m[0].startsWith('$') && /[{}]/.test(m[0]),
  );
  if (braces.length) {
    console.error(`[patch] ${rel}: a literal with braces would break when interpolated: ${braces[0][0]}`);
    process.exit(1);
  }

  // State first: `/libsdl/Celeste/` is a prefix of nothing else, but
  // `/libsdl/` is a prefix of it.
  const out = source
    .replace(STATE_PREFIX, '$"{CelestePaths.State}/')
    .replace(INSTALL_PREFIX, '$"{CelestePaths.Install}/');

  const left = out.match(/\/libsdl\//g);
  if (left) {
    console.error(`[patch] ${rel}: ${left.length} path literal(s) left unrewritten`);
    process.exit(1);
  }
  return out;
}

for (const rel of ['loader/Celeste.cs', 'loader/Patcher.cs', 'loader/CelesteBootstrap.cs']) {
  let count = 0;
  edit(rel, (source) => {
    count = (source.match(/\/libsdl\//g) ?? []).length;
    return rewritePaths(source, rel);
  });
  changes.push(`${rel}: ${count} path literal(s) → CelestePaths`);
}

// ------------------------------------------------------ the way it is set --

{
  const rel = 'loader/CelesteBootstrap.cs';
  edit(rel, (source) => {
    const withParam = source.replace(
      /(public static async Task MountFilesystems\(string root, string\[\] rawDlls)(\))/,
      '$1, string storageNamespace = ""$2',
    );
    if (withParam === source) return source;

    // Before mount_opfs(), so nothing has looked at a path yet.
    return withParam.replace(
      /(\n[ \t]*try\n[ \t]*\{\n)([ \t]*)(int ret = mount_opfs\(\);)/,
      `$1$2CelestePaths.UseNamespace(storageNamespace);\n\n$2$3`,
    );
  });
  changes.push(`${rel}: MountFilesystems takes storageNamespace`);
}

// --------------------------------------------------------- Everest's paths --
//
// `patcher/` is compiled into Celeste.Mod.mm by MonoMod and never references
// the loader, so this reads what UseNamespace() put in the environment. Without
// it the game stages under the namespace and Everest looks for mods at the old
// path, which presents as "no mods" rather than as an error.

{
  const rel = 'patcher/EverestPaths.cs';
  edit(rel, (source) => {
    const after = source.replace(
      /public static string PathMods \{ get \{ return "[^"]*"; \}/,
      'public static string PathMods { get { return (System.Environment.GetEnvironmentVariable("CELESTE_STATE") ?? "/libsdl/Celeste") + "/Mods"; }',
    );
    if (after === source) {
      console.error(`[patch] ${rel}: could not find PathMods`);
      process.exit(1);
    }
    return after;
  });
  changes.push(`${rel}: PathMods follows CELESTE_STATE`);
}

// ------------------------------------------------------------- the default --
//
// Baked in so a runtime built here namespaces itself even when the host says
// nothing. A host that wants the old layout passes an empty string.

if (namespace) {
  const rel = 'loader/CelestePaths.cs';
  edit(rel, (source) =>
    source.replace(
      'public static void UseNamespace(string ns)\n    {\n        if (string.IsNullOrEmpty(ns))',
      `public static void UseNamespace(string ns)
    {
        // Built with a default namespace, so a host that says nothing still
        // gets one. Pass "-" for the original root-level layout.
        if (ns == null || ns.Length == 0) ns = ${JSON.stringify(namespace)};
        if (ns == "-")`,
    ),
  );
  changes.push(`loader/CelestePaths.cs: default namespace "${namespace}"`);
}

for (const change of changes) console.log(`[patch] ${change}`);
